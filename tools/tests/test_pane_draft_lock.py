#!/usr/bin/env python3
"""Замок блока 4: кнопка запуска гаснет на время работы, «ДАЛЕЕ» - только по факту конца.

Живой случай (владелец): «Нажимаем „Создать черновик“, запускается работа LLM, но кнопка
всё равно остаётся доступной! Есть шанс вызвать лишние повторные задачи… потом кнопка
меняет название на „Перегенерировать“ но в этот момент „ДАЛЕЕ“ ещё не была доступна,
а значит черновик ещё не завершён. И ты пишешь „Финализирую: metadata → маркер…“ - а
доступ к „ДАЛЕЕ“ уже появился. Надо выставлять флаг о завершении по факту ВСЕХ
финальных дел».

Отсюда три правила, и все три тут проверяются:
1. Кнопка «✎» блокируется на ВСЮ работу (`draftWork`), а не только когда файлы уже
   появились: первые минуты (агент читает источник) кнопка была живой и пускала вторую
   задачу в тот же каталог;
2. «Перегенерировать с учётом замечаний» - подпись ГОТОВОГО черновика (`draftSettled`),
   а не «каталог найден» (`hasDraft`): иначе она обещала перегенерацию того, что ещё
   пишется;
3. «ДАЛЕЕ», «Критика» и запись в профиль открываются на «маркер ЕСТЬ и агент СВОБОДЕН»
   (`draftSettled = draftReady && !draftWork`): маркер агент кладёт до финальных проверок,
   и панель, доверявшая только ему, открывала запись на середине работы.

Запуск: python -B tools/tests/test_pane_draft_lock.py
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PLUGIN = REPO / "hermes" / "desktop-plugins" / "b2s" / "plugin.js"

checks: list[tuple[str, bool]] = []


def check(name: str, ok: bool, detail: str = "", note: str = "") -> None:
    checks.append((name, ok))
    print(("  OK   " if ok else "  FAIL ") + name +
          (f" - {note}" if note else (f" - {detail}" if detail else "")))


raw = PLUGIN.read_text(encoding="utf-8")
check("plugin.js читается", len(raw) > 10000, str(PLUGIN))

print("=== 1. понятие «работа по черновику» и «черновик устоялся» ===")
check("`draftWork` собран из ожидания, генерации и занятости агента",
      "const draftWork = !!(draftWait || llmTurn)" in raw,
      "draftWork должен включать draftWait (задание ушло) и llmTurn (агент занят)")
check("`draftSettled` = маркер готовности И агент свободен",
      "const draftSettled = !!(draftReady && !draftWork)" in raw,
      "без этого маркера достаточно, чтобы открыть запись на середине работы")

print("=== 2. кнопка «✎» гаснет на время работы ===")
check("кнопка запуска заблокирована по `draftWork`, а не по «файлы уже есть»",
      "disabled: !!busy || draftWork," in raw,
      "кнопка снова живая первые минуты генерации - второй запуск в тот же каталог")
check("старый замок «только по draftWriting» не вернулся",
      "disabled: !!busy || draftWriting," not in raw,
      "кнопка гасла лишь когда файлы уже появились: окно двойного запуска открыто")
check("тултип кнопки называет причину отказа при работающем задании",
      "задание черновика уже в работе - второй запуск запрещён" in raw and
      "агент ещё завершает работу над черновиком - второй запуск запрещён" in raw,
      "кнопка гаснет молча - владелец не понимает, почему она не нажимается")

print("=== 3. подпись кнопки - по готовности, а не по «каталог найден» ===")
check("«Перегенерировать с учётом замечаний» требует `draftSettled`",
      "cutSpan(draftSettled ? 'Перегенерировать с учётом замечаний' : 'Сделать черновик'," in raw,
      "подпись переключалась на `hasDraft`: обещала перегенерацию того, что ещё пишется")
check("старая подпись по `hasDraft` не вернулась",
      "hasDraft ? 'Перегенерировать с учётом замечаний'" not in raw,
      "вернулся контракт «каталог найден = можно перегенерировать»")
check("тултип кнопки тоже по `draftSettled`",
      "draftSettled ? TIP.redraft : TIP.draft" in raw,
      "тултип обещает не то, что делает кнопка")

print("=== 4. переходы и запись ждут конца работы ===")
check("«ДАЛЕЕ» блока 4 заперта по `draftSettled`",
      "disabled: !!busy || !draftSettled || !block2Passed," in raw,
      "прыжок в блок 5 на середине финальных дел агента")
check("`next4` проверяет `draftSettled` и различает «пишется» и «агент дописывает»",
      "if (!draftSettled) {" in raw and
      "маркер готовности уже лежит, но агент ещё завершает работу над черновиком" in raw,
      "переход проверял только маркер: агент правил черновик, а человек уже уходил вперёд")
check("«Критика» заперта по `draftSettled`",
      "disabled: !!busy || !draftSettled," in raw,
      "критиковать то, что ещё пишется, - платная задача впустую")
check("запись в профиль заперта по `draftSettled`",
      "disabled: !!busy || !draftSettled || !readySeen || !!installed || nameWarn || nameBad || !block2Passed," in raw,
      "в профиль уедет черновик, который агент ещё правит")
check("состояние блока 4 различает «маркер есть, агент дописывает»",
      "'⏳ маркер есть, агент дописывает'" in raw and
      "'⏳ агент дописывает черновик'" in raw,
      "блок молчит о том, что маркер уже лежит, а работа идёт")

print("=== 5. вотчер ждёт освобождения агента ===")
check("вотчер объявляет готовность только при свободном агенте",
      "if (out.ready && !llmBusyRef.current) {" in raw,
      "вотчер верил первому маркеру и открывал запись, пока агент ещё работал")
check("вотчер говорит вслух, что маркер есть, а агент ещё завершает",
      "но агент ещё завершает работу - жду, пока он освободится" in raw,
      "панель молчит в самом опасном состоянии - «уже готово? или ещё нет?»")
check("занятость агента читается через ref (вотчер живёт в setInterval)",
      "const llmBusyRef = useRef(false)" in raw and
      "llmBusyRef.current = !!(llmSid && busyMap && busyMap[llmSid])" in raw,
      "в setInterval виден только ref: свежий стейт туда не доезжает")
check("задание без файлов снимает ожидание, когда агент освободился",
      "задание ушло, но каталога черновика в staging нет - смотри ответ агента в чате" in raw,
      "кнопка запуска осталась бы запертой до 30-минутного дедлайна")

print("=== 6. протокол задания: маркер - последним действием ===")
check("задание требует порядок «проверки → маркер»",
      "Закончив (именно в этом порядке):" in raw and
      "маркер готовности - ПОСЛЕДНЕЕ действие" in raw,
      "агент ставил READY.json до финальных проверок - панель открывала «ДАЛЕЕ» раньше времени")
check("задание требует переписать маркер, если после него правили файлы",
      "если после маркера всё же правил файлы, перезапиши маркер заново" in raw,
      "правки после маркера никому не видны - запись уедет по старому состоянию")

ok_all = all(ok for _, ok in checks)
bad = [n for n, ok in checks if not ok]
print(f"\nпроверок: {len(checks)}, провалов: {len(bad)}")
if bad:
    print("провалено: " + "; ".join(bad))
raise SystemExit(0 if ok_all else 1)
