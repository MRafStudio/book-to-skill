#!/usr/bin/env python3
"""Сторож зелёной рамки шага 3 («Категория и имя скилла»).

Зачем: цвет рамки у каждого шага панель выводила из РЕЗУЛЬТАТА шага - проба
источника (шаг 1), отчёт разбора (шаг 2), готовность черновика (шаг 4),
предпросмотр или установка (шаг 5). У шага 3 такого результата нет: он спрашивает
реквизиты записи, и его условие тона знало только ``'bad'`` и ``null`` - то есть
зелёный был недостижим В ПРИНЦИПЕ. Владелец: «если в группе 3 нажать кнопку
"ДАЛЕЕ" её граница не окрашивается зелёным, не смотря на то, что в ней ошибок не
обнаружено и все требования исполнены». Решение владельца - вести факт прохождения
шага флагом ``nameSeen`` (полная аналогия ``readySeen`` у шага 4), а не красить по
заполненности полей: зелёный значит «по реквизитам пошли дальше».

Что проверяем
-------------
1. флаг прохождения шага 3 объявлен как состояние панели;
2. отмечается он в ``next3`` и ПОСЛЕ проверок имени - клик, который никуда не
   пустил, прохождением не считается (иначе зелёный врал бы на отказе);
3. зелёный в условии тона блока 3 есть, зависит от флага И от пройденного шага 2;
4. красный (пустое или негодное имя) сохранил приоритет над зелёным;
5. полный сброс панели флаг снимает - иначе зелёный переживёт сброс и будет
   показывать прохождение шага, которого в новой сессии не было;
6. флагов прохождения в панели ровно два (шаг 3 и шаг 4) - третий не завёлся.

Запуск: python -B tools/tests/test_pane_step3.py
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PLUGIN = REPO / "hermes" / "desktop-plugins" / "b2s" / "plugin.js"

checks: list[tuple[str, bool]] = []


def check(name: str, ok: bool, detail: str = "", note: str = "") -> None:
    checks.append((name, ok))
    if ok:
        print(f"  OK   {name}" + (f" - {note}" if note else ""))
    else:
        print(f"  FAIL {name}" + (f" - {detail}" if detail else ""))


raw = PLUGIN.read_text(encoding="utf-8")
check("plugin.js читается", len(raw) > 10000, str(PLUGIN))

# Тело next3 - от его объявления до объявления next4; там же ищем отметку прохождения.
i3 = raw.index("const next3 = ()")
i4 = raw.index("const next4 = ()")
body3 = raw[i3:i4]

check("флаг прохождения шага 3 объявлен как состояние панели",
      "const [nameSeen, setNameSeen] = useState(false)" in raw,
      "нет пары useState для nameSeen - отметка прохождения потеряется между рендерами",
      note="nameSeen")

check("next3 отмечает прохождение шага 3",
      "setNameSeen(true)" in body3,
      "next3 не отмечает прохождение: рамка шага 3 останется нейтральной навсегда")

mark = body3.index("setNameSeen(true)")
check("отметка стоит ПОСЛЕ проверок имени, а не до них",
      mark > body3.index("if (nameBad)") and mark < body3.index("onlyB(4)"),
      "отметка поднята выше проверок: отказной клик (пустое или негодное имя) "
      "покрасит шаг зелёным «пройдено»",
      note="отметка после block2Passed/nameWarn/nameBad")

check("next4 по-прежнему отмечает прохождение шага 4",
      "setReadySeen(true)" in raw[i4:i4 + 900],
      "правка шага 3 снесла отметку readySeen у шага 4 - кнопка записи в шаге 5 "
      "перестанет активироваться")

# Условие тона блока 3: от `n: 3,` до `n: 4,` - там же кнопка и её подсказки.
seg3 = raw[raw.index("        n: 3,"):raw.index("        n: 4,")]

check("зелёный по флагу прохождения есть в условии тона блока 3",
      "((nameSeen && block2Passed) ? 'done' : null)" in seg3,
      "условие тона снова знает только 'bad' и null - зелёный недостижим, "
      "жалоба владельца возвращается",
      note="tone: ((nameWarn || nameBad) && block2Passed) ? 'bad' : "
           "((nameSeen && block2Passed) ? 'done' : null)")

check("красный приоритетнее зелёного (пустое или негодное имя не зеленеет)",
      "((nameWarn || nameBad) && block2Passed)" in seg3,
      "красная ветка ушла из условия: шаг с пустым/негодным именем может стать зелёным")

check("зелёный не выводится из заполненности полей",
      seg3.count("'done'") == 1,
      "в блоке 3 больше одного 'done' - зелёный снова появляется без прохождения шага",
      note="единственный 'done' - по nameSeen")

check("полный сброс панели снимает флаг прохождения шага 3",
      "setPreview(null); setReadySeen(false); setNameSeen(false); setDraftWait(false)" in raw,
      "resetAfterPurge не гасит nameSeen: после сброса панель покажет шаг 3 пройденным")

flags = sorted(re.findall(r"const \[(\w+Seen), set\w+Seen\] = useState\(false\)", raw))
check("флагов прохождения в панели ровно два (шаг 3 и шаг 4)",
      flags == ["nameSeen", "readySeen"],
      f"найдено {flags}: третий флаг прохождения завёлся по недосмотру")

print(f"\nпроверок: {len(checks)}, провалов: {sum(1 for _, ok in checks if not ok)}")
if any(not ok for _, ok in checks):
    print("провалено: " + "; ".join(name for name, ok in checks if not ok))
    sys.exit(1)
print("ВСЁ ЗЕЛЁНОЕ: зелёная рамка шага 3 появляется только по факту прохождения шага")
